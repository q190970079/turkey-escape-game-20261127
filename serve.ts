// Tiny static server for local play-testing: serves game/ on
// http://localhost:8080 with no build step and no dependencies.
// Run with `node serve.ts` from this directory.
import { createServer } from 'node:http';
import { readFile } from 'node:fs/promises';
import { join, extname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = fileURLToPath(new URL('.', import.meta.url));
const types = {
  '.html': 'text/html',
  '.js': 'text/javascript',
  '.mjs': 'text/javascript',
  '.css': 'text/css',
  '.json': 'application/json',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
};

const server = createServer(async (req, res) => {
  const path = req.url === '/' ? '/index.html' : (req.url || '/index.html').split('?')[0];
  try {
    const body = await readFile(join(here, 'game', path));
    res.writeHead(200, { 'content-type': types[extname(path)] || 'application/octet-stream' });
    res.end(body);
  } catch {
    res.writeHead(404);
    res.end('not found');
  }
});

server.listen(8080, () => {
  console.log('Turkey\'s Great Escape at http://localhost:8080');
});
